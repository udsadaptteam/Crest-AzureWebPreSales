function splitFullName(fullName) {
  if (!fullName) return { FirstName: "", LastName: "" };

  const parts = fullName.trim().split(/\s+/);

  return {
    FirstName: parts[0] || "",
    LastName: parts.length > 1 ? parts[parts.length - 1] : ""
  };
}

